def analyze_image_file(file_path: str, prompt: str) -> Dict[str, Any]:
    path = Path(file_path)
    if not path.exists():
        return {"success": False, "output": "Uploaded image file not found."}

    img = Image.open(str(path))
    width, height = img.size
    fmt = img.format or path.suffix.lstrip(".").upper()
    mode = img.mode
    gray = ImageOps.grayscale(img)
    stat = ImageStat.Stat(gray)
    brightness = round(stat.mean[0], 1)
    contrast = round(stat.stddev[0], 1)
    img.close()

    ai_explanation = ask_llm(
        prompt=(
            f"An image file '{path.name}' ({width}x{height}px, {fmt}, mode={mode}, brightness={brightness}/255) "
            f"was uploaded. User question: {prompt}"
        ),
        system_prompt="You are the Omniscient AI Vision & Diagram Analyst.",
    )["content"]

    report = (
        f"### Image Vision & Structural Analysis (`{path.name}`)\n\n"
        f"- **Resolution**: `{width} x {height} px` | **Format**: `{fmt}` | **Color Mode**: `{mode}`\n"
        f"- **Luminance & Contrast**: Mean `{brightness}/255`, Contrast StdDev `{contrast}`\n\n"
        f"{ai_explanation}"
    )
    return {
        "success": True,
        "output": report,
        "image_metadata": {"width": width, "height": height, "format": fmt, "mode": mode},
    }
